package org.umn.jalankita.data.repository

import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flowOf
import kotlinx.coroutines.flow.map
import org.umn.jalankita.data.local.NotificationDao
import org.umn.jalankita.data.local.NotificationEntity
import org.umn.jalankita.data.local.ReportDao
import org.umn.jalankita.data.local.ReportEntity
import org.umn.jalankita.data.local.ReporterDao
import org.umn.jalankita.data.local.ReporterEntity
import org.umn.jalankita.data.local.toDomain
import org.umn.jalankita.model.DamageCategory
import org.umn.jalankita.util.ConnectivityMonitor
import org.umn.jalankita.model.AppNotification
import org.umn.jalankita.model.Report
import org.umn.jalankita.model.ReporterProfile
import org.umn.jalankita.model.ReportStatus
import org.umn.jalankita.model.SyncStatus
import java.util.UUID

/**
 * Coordinates the local store and (once configured) the remote one.
 *
 * Reads always come from Room so the UI never waits on the network.
 */
open class ReportRepository(
    private val reportDao: ReportDao,
    private val notificationDao: NotificationDao,
    private val networkMonitor: ConnectivityMonitor,
    private val syncTrigger: ReportSyncTrigger = NoOpSyncTrigger,
    private val reporterDao: ReporterDao? = null,
) {

    fun observeReports(userId: String): Flow<List<Report>> =
        reportDao.observeReportsByUser(userId).map { rows -> rows.map { it.toDomain() } }

    /**
     * Every report on the device, mine and the community's — what the map and
     * the proximity alerts care about, since a pothole is a hazard regardless of
     * who reported it.
     */
    fun observeCommunityReports(): Flow<List<Report>> =
        reportDao.observeAllReports().map { rows -> rows.map { it.toDomain() } }

    fun observeReportsByReporter(reporterId: String): Flow<List<Report>> =
        reportDao.observeReportsByReporter(reporterId).map { rows -> rows.map { it.toDomain() } }

    // --- Reporters ---

    fun observeReporter(reporterId: String): Flow<ReporterProfile?> =
        reporterDao?.observeReporter(reporterId)?.map { it?.toDomain() } ?: flowOf(null)

    suspend fun upsertReporters(reporters: List<ReporterEntity>) {
        reporterDao?.upsertAll(reporters)
    }

    /**
     * Recomputes the signed-in user's own track record from their local rows,
     * naming any older row that predates reporter identity.
     */
    suspend fun refreshReporterStats(reporterId: String, name: String) {
        reportDao.backfillReporterName(reporterId, name)
        reporterDao?.refreshFromReports(reporterId, name, System.currentTimeMillis())
    }

    fun observeReport(reportId: String): Flow<Report?> =
        reportDao.observeReportById(reportId).map { it?.toDomain() }

    fun observeUnsyncedCount(userId: String): Flow<Int> = reportDao.observeUnsyncedCount(userId)

    suspend fun getReport(reportId: String): Report? = reportDao.getReportById(reportId)?.toDomain()

    suspend fun getReports(userId: String): List<Report> =
        reportDao.getReportsByUser(userId).map { it.toDomain() }

    suspend fun getPendingSyncReports(): List<Report> =
        reportDao.getPendingSyncReports().map { it.toDomain() }

    // --- Writing ---

    /**
     * Room first, always.
     *
     * The row exists before any network call is attempted, so the UI can show the
     * report immediately and nothing is lost if the upload never happens. [reportId]
     * is generated by the caller when the draft starts and is reused on every retry,
     * which is what keeps sync idempotent.
     */
    suspend fun submitReport(
        reportId: String,
        userId: String,
        reporterName: String?,
        photoPath: String?,
        category: DamageCategory,
        description: String?,
        latitude: Double,
        longitude: Double,
        streetName: String?,
    ): SubmitOutcome {
        val now = System.currentTimeMillis()
        val entity = ReportEntity(
            id = reportId,
            userId = userId,
            reporterName = reporterName,
            photoPath = photoPath,
            photoRemoteUrl = null,
            category = category.id,
            description = description?.takeIf { it.isNotBlank() },
            latitude = latitude,
            longitude = longitude,
            streetName = streetName?.takeIf { it.isNotBlank() },
            reportStatus = ReportStatus.PENDING.id,
            syncStatus = SyncStatus.PENDING_SYNC.id,
            createdAt = now,
            updatedAt = now,
        )
        reportDao.insertReport(entity)
        // The reporter's own card should count this the moment it is stored.
        reporterName?.let { refreshReporterStats(userId, it) }

        // Only try an immediate send when there is something to send over.
        val synced = if (networkMonitor.currentlyOnline()) {
            runCatching { syncTrigger.syncNow(reportId) }.getOrDefault(false)
        } else {
            false
        }

        if (synced) {
            // The sync engine already recorded "Laporan berhasil dikirim"; adding a
            // second notification here would double it.
        } else {
            // Not delivered yet: hand it to WorkManager and tell the user plainly
            // that waiting is normal, not a failure.
            syncTrigger.requestSync()
            addNotification(
                userId = userId,
                title = "Laporan tersimpan di perangkat",
                message = "Laporan ${category.label} akan dikirim otomatis saat koneksi tersedia.",
                reportId = reportId,
            )
        }

        return SubmitOutcome(report = reportDao.getReportById(reportId)!!.toDomain(), synced = synced)
    }

    /** Fills in a street name that could not be resolved while offline. */
    suspend fun fillMissingStreetName(reportId: String, streetName: String) =
        reportDao.fillMissingStreetName(reportId, streetName)

    suspend fun reportsMissingStreetName(userId: String): List<Report> =
        reportDao.getReportsWithoutStreetName(userId).map { it.toDomain() }

    fun requestSync() = syncTrigger.requestSync()

    // --- Notifications ---

    fun observeNotifications(userId: String): Flow<List<AppNotification>> =
        notificationDao.observeByUser(userId).map { rows -> rows.map { it.toDomain() } }

    fun observeUnreadNotificationCount(userId: String): Flow<Int> =
        notificationDao.observeUnreadCount(userId)

    suspend fun markNotificationRead(notificationId: String) =
        notificationDao.markAsRead(notificationId)

    suspend fun markAllNotificationsRead(userId: String) = notificationDao.markAllAsRead(userId)

    /** Records an in-app notification for a report lifecycle event. */
    suspend fun addNotification(
        userId: String,
        title: String,
        message: String,
        reportId: String? = null,
    ) {
        notificationDao.insert(
            NotificationEntity(
                id = UUID.randomUUID().toString(),
                userId = userId,
                title = title,
                message = message,
                reportId = reportId,
                isRead = false,
                createdAt = System.currentTimeMillis(),
            ),
        )
    }

    // --- Derived statistics for the profile screen ---

    fun observeStats(userId: String): Flow<ReportStats> =
        reportDao.observeReportsByUser(userId).map { rows -> rows.map { it.toDomain() }.stats() }
}

/** Counts derived from a list already in memory — no extra query. */
fun List<Report>.stats(): ReportStats = ReportStats(
    total = size,
    synced = count { it.syncStatus == SyncStatus.SYNCED },
    pending = count { it.reportStatus == ReportStatus.PENDING },
    inProgress = count {
        it.reportStatus == ReportStatus.VERIFIED || it.reportStatus == ReportStatus.IN_PROGRESS
    },
    completed = count { it.reportStatus == ReportStatus.COMPLETED },
)

data class SubmitOutcome(
    val report: Report,
    val synced: Boolean,
)

data class ReportStats(
    val total: Int = 0,
    /** Reports that reached the server. Device bookkeeping, not workflow state. */
    val synced: Int = 0,
    val pending: Int = 0,
    val inProgress: Int = 0,
    val completed: Int = 0,
)
